function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Границы слова здесь буквенные, без цифр: «ТК» не должна срабатывать внутри
// слова, но «ТК-2» — нормальный случай.
function reForAbbr(abbr: string): RegExp {
  return new RegExp(`(?<![А-Яа-яA-Za-z])${escapeRe(abbr)}(?![А-Яа-яA-Za-z])`);
}

// По убыванию длины: «ТК РФ» проверяем раньше «ТК», иначе короткая
// аббревиатура съест начало длинной.
const ABBR_PATTERNS = Object.entries(ABBREVIATIONS)
  .sort(([a], [b]) => b.length - a.length)
  .map(([abbr, full]) => ({ re: reForAbbr(abbr), abbr, full }));

/** «… ТК …» → «… ТК (Трудовой кодекс) …». Оригинальная форма сохраняется. */
export function expandAbbreviations(text: string): string {
  if (!text) return text;
  let out = text;
  for (const { re, abbr, full } of ABBR_PATTERNS) {
    // Если полная форма уже рядом — пропускаем, чтобы не плодить «ТК (…) (…)».
    if (out.toLowerCase().includes(full.toLowerCase())) continue;
    // Регэксп без флага g — замена только первого вхождения (count=1 в Python).
    out = out.replace(re, `${abbr} (${full})`);
  }
  return out;
}

