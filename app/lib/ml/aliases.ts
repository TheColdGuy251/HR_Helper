// В Python `\w` и `\b` знают кириллицу, в JS — только ASCII (из-за чего, скажем,
// «зп\b» не сматчилось бы вовсе). Подставляем юникод-класс и корректную границу.
const WORD = '0-9A-Za-zА-Яа-яЁё_';
const BOUND = `(?:(?<![${WORD}])(?=[${WORD}])|(?<=[${WORD}])(?![${WORD}]))`;

const SYN_PATTERNS = SYNONYMS.map(([trigger, legal]) => ({
  re: new RegExp(trigger.replace(/\\b/g, BOUND).replace(/\\w/g, `[${WORD}]`), 'i'),
  legal,
}));

/** Дописывает юридические термины по разговорным триггерам. */
export function expandSynonyms(text: string): string {
  if (!text) return text;
  const low = text.toLowerCase();
  const additions: string[] = [];
  for (const { re, legal } of SYN_PATTERNS) {
    if (re.test(low) && !low.includes(legal.toLowerCase())) additions.push(legal);
  }
  if (!additions.length) return text;
  return `${text} [${additions.join(' ; ')}]`;
}

/**
 * Поисковый запрос: аббревиатуры + синонимы. Порт `_maybe_hyde` без самой
 * HyDE-части (генерация гипотетического параграфа LLM осталась в FastAPI —
 * это опциональная ветка, включаемая флагом rag_use_hyde).
 */
export function prepareSearchQuery(query: string): string {
  return expandSynonyms(expandAbbreviations(query));
}
